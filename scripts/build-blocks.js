// Builds templates/blocks.json (the Persona starter blocks) from templates/starter-blocks.json + templates/presets.json,
// and writes the matching seed rows into supabase/character-blocks.sql. Run: node scripts/build-blocks.js
"use strict";
const fs = require("fs"), path = require("path");
const Blocks = require("../lib/blocks.js");
const root = path.join(__dirname, "..");
const read = (f) => JSON.parse(fs.readFileSync(path.join(root, f), "utf8"));

const starters = read("templates/starter-blocks.json").blocks;
const presets = read("templates/presets.json");
const FROM = { camera: ["camera", "cam-"], light: ["lighting", "light-"], location: ["location", "loc-"], pose: ["pose", "pose-"] };
const out = [];
starters.forEach((b) => out.push(Blocks.validate(Object.assign({ author: "Persona" }, b))));
Object.keys(FROM).forEach((t) => {
  const [group, prefix] = FROM[t];
  presets[group].forEach((p) => {
    const data = { description: p.prompt, preset: p.id };
    if (p.shop) data.full_outfit = true;
    out.push(Blocks.validate({ type: t, name: p.id.replace(prefix, ""), version: 1, title: p.name, author: "Persona", data }));
  });
});
const seen = {};
out.forEach((b) => { if (seen[b.address]) throw new Error("Duplicate " + b.address); seen[b.address] = 1; });
fs.writeFileSync(path.join(root, "templates/blocks.json"), JSON.stringify({
  about: "Persona starter blocks. Generated by scripts/build-blocks.js; edit templates/starter-blocks.json or presets.json instead.",
  format: "templates/block-template.json",
  blocks: out.map(Blocks.share),
}, null, 1) + "\n");

const q = (s) => (s == null ? "null" : "'" + String(s).replace(/'/g, "''") + "'");
const rows = out.map((b) => "  (" + [q(b.address), q(b.type), q(b.name), b.version, q(b.title), q(JSON.stringify(b.data)) + "::jsonb",
  q(b.preview), "array[" + b.tags.map(q).join(",") + "]::text[]", q(b.remix_of), q(b.type === "face" ? "invented" : null), q("Persona")].join(", ") + ")");
// Older versions first so remix_of links point at rows that already exist.
const seed = "insert into public.blocks (address, type, name, version, title, data, preview_url, tags, remix_of, likeness, author_name) values\n" +
  rows.join(",\n") + "\non conflict (address) do update set title = excluded.title, data = excluded.data, tags = excluded.tags, preview_url = excluded.preview_url;";
const sqlPath = path.join(root, "supabase/character-blocks.sql");
const sql = fs.readFileSync(sqlPath, "utf8").replace(/-- STARTERS BEGIN[\s\S]*-- STARTERS END/, "-- STARTERS BEGIN\n" + seed + "\n-- STARTERS END");
fs.writeFileSync(sqlPath, sql);
console.log(out.length + " starter blocks written.");
